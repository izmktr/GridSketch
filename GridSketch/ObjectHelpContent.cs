namespace GridSketch;

internal static class ObjectHelpContent
{
    internal static (string Summary, List<(string Heading, string Body)> Sections) For(SceneObject node)
    {
        var sections = new List<(string Heading, string Body)>();
        void Add(string heading, string body) => sections.Add((heading, body));
        string summary;
        switch (node.Kind)
        {
            case ObjectKind.Canvas:
                summary = "書き出す画像や用紙の範囲を決める";
                Add("自動サイズと固定サイズ", "自動は、配置した内容が収まる大きさに出力範囲を更新します。パズルを作りながら完成サイズを決めたい場合に使います。周囲の余白も指定できます。\n\n固定は、幅・高さと出力範囲の左上を指定します。決まった紙面に内容を配置したい場合に使います。範囲外のオブジェクトは削除されず、書き出し時に切り取られます。");
                Add("単位・用紙・解像度", "pxは画像の画素数、mmは用紙の寸法です。用紙プリセットや縦横の入れ替えも使えます。\n\nmm指定では、同じ用紙サイズでもdpiを上げるとPNGの画素数が増えます。px指定・自動サイズでは、dpiは画素数から用紙寸法への換算に使います。dpiの変更だけではオブジェクト自体を移動・拡縮しません。");
                Add("背景と書き出し", "背景色はキャンバスで設定します。PNG・PDFはキャンバスの出力範囲を使います。形式ごとの設定は「ファイル → エクスポート設定」で変更します。");
                break;
            case ObjectKind.Grid:
                summary = "マス数・マスの大きさ・余白の基準を作る";
                Add("グリッドの作り方", "列数・行数と、1マスの大きさを指定します。グリッド自体は線を描かず、子の罫線・領域枠・文字などを配置する基準になります。グリッド全体を移動・回転すると、その中の内容も一緒に動きます。");
                Add("マス内余白", "左右と上下を別々に設定できます。マス配置画像や、余白の内側を使う文字・セル塗り・マス切り替えの配置に使います。余白を変えてもマスの間隔自体は変わりません。");
                Add("サイズ変更時の内容", "外枠・内枠の罫線はマス数に追従します。個別罫線や指定マスの枠は範囲内に調整します。文字・画像・塗り・マス切り替えの配置が縮小後の範囲外に残る場合は変更できません。先に内容を移動・削除してください。");
                break;
            case ObjectKind.Group:
                summary = "複数のオブジェクトをまとめて扱う";
                Add("一括変形用と整理用", "一括変形用では、子をまとめて移動・回転できます。整理用では表示・ロックをまとめて管理し、親の配置範囲を子へ渡します。\n\n罫線やグリッド文字など、所属グリッドに従う子を含めると整理用へ自動変換します。移動・回転・拡縮がある場合は変換できません。対象の子を取り除くと「一括変形用に戻す」が使えます。");
                Add("自身の幅・高さと内側の余白", "固定の配置範囲を使うと、子はグループ自身の幅・高さを基準に配置されます。子のサイズを変えても、この範囲は自動で変わりません。範囲の外へ出た子を切り取る設定ではありません。\n\n「子に内側の範囲も渡す」を有効にすると、左右・上下の余白を除いた範囲も子が選べます。右や下に空きを残した部品にも使えます。");
                Add("グループ化・部品として再利用", "同じ親の下で連続したレイヤーを複数選択し、グループ化できます。まとめられない組み合わせは操作できません。\n\n「部品 → 選択グループを登録」で再利用できます。追加される部品は独立したコピーです。登録元の編集は配置済みコピーに反映しません。");
                break;
            case ObjectKind.Border:
                summary = node.ConnectCellCenters ? "隣り合うマスの中心を線でつなぐ" : "マスの境界に沿って線を描く";
                Add("クリック・ドラッグで編集", node.ConnectCellCenters
                    ? "「マス・辺を編集」で、隣り合うマスの中心間をクリックして線を切り替えます。縦・横のつながりを作れます。1マスしかない方向には中心間の線はありません。\n\nドラッグは開始位置の変更後のON／OFFを保って続けて編集します。"
                    : "「マス・辺を編集」でマスの辺をクリックすると、線の有無が切り替わります。ドラッグは開始位置の変更後のON／OFFを保って続けて編集します。迷路の壁や区切り線に使えます。");
                Add("線の見た目と端・角", "1オブジェクトの線には共通の色・太さ・線種を指定します。違う見た目の線は別オブジェクトに分けます。\n\n「中央まで」は端点で止まります。「四角」は線幅の半分だけ端を延長し、縦横の接続部分を四角く埋めます。「丸」は線幅を直径とする丸い端になります。");
                Add("辺の一括設定", "プロパティの図をクリックして、外側や内側などの線をまとめて設定できます。Shift＋クリックで範囲を選ぶと、その範囲が対象になります。未選択なら全体に適用します。中心罫線ではマスの中心を結ぶ範囲が対象です。");
                break;
            case ObjectKind.CellFrame:
                summary = "マスを結合して領域の外周線と内部線を描く";
                Add("領域の作成と結合", "初期状態は空です。空のマスからドラッグすると、通ったマスが結合した領域になります。対象マスをクリックして削除できます。隣接していても、結合していなければ別領域です。対象マス間の辺をクリック・ドラッグすると結合を切り替えます。別の経路で結合しているマスは同じ領域に属します。");
                Add("外周線と内部線", "外周線は領域の輪郭、内部線は同じ領域のマス同士の境界です。それぞれ色・線種・太さを指定でき、線種を「なし」にすると非表示になります。線種はボタンで選択します。外周線と内部線が重なる部分は外周線の色を使います。");
                Add("外周線の引き込み", "0はグリッド罫線上、正の値は内側、負の値は外側へ移動します。単位はpxです。内部線はグリッド罫線上に置かれ、外周線を内側へ引き込んだ場合はその内側で止まります。同じ領域枠内の線は重なっても濃くなりません。");
                Add("範囲の操作", "Shift＋クリックで範囲を選び、「選択範囲を結合して領域を作成」「選択範囲の結合を解除」「選択範囲の領域を削除」を使えます。");
                break;
            case ObjectKind.Fill:
                summary = "マスに背景色や黒マスを付ける";
                Add("マスを塗る", "「マス・辺を編集」でクリックすると塗りが切り替わります。ドラッグは開始マスの変更後の状態を保って連続適用します。Shift＋クリックで選んだ範囲は「選択範囲の塗りを削除」でまとめて空にできます。");
                Add("塗る範囲と色", "「マス全体」はマスの境界まで塗ります。「余白の内側」は親グリッドの左右・上下の余白を除いて塗ります。1オブジェクトの塗り色は共通です。色を分けたい場合はセル塗りを複数使います。");
                break;
            case ObjectKind.GridText:
                summary = "マスに文字や数字を入力する";
                Add("右・下・□の入力", "「マス・辺を編集」でマスを選ぶとキーボードで入力できます。同じマスをクリックするたびに、右 → 下 → □ → 右と切り替わります。\n\n右・下は1文字ずつ次のマスへ進み、既存文字を上書きします。□は同じマスの末尾へ追記します。例えば2桁の数字もひとまとめで中央揃えにし、縮小せずマスの外にも描画します。IMEは変換確定後に反映します。");
                Add("削除・移動・入力の停止", "Deleteはそのマスを空にします。右・下でのBackspaceは1マス戻って削除、□では同じマスの末尾1文字を削除します。矢印キーで入力先を移動できます。\n\nグリッドの端で入力が止まります。セル塗りのあるマスにも入力できます。複数文字が入り切らない場合は途中まで入力せず、内容を維持します。次のマスを選び直して続けてください。");
                Add("配置・フォント・縁取り", "文字はマス全体を基準に配置し、揃え方は3×3のアイコンから、左上・上・右上・左・中央・右・左下・下・右下の9方向を選べます。文字の大きさは文字サイズで調整します。通常の1文字入力は縁取りも含めて領域に収めます。□で入力した文字列は常に中央揃えで、マス幅による縮小や切り取りはしません。\n\nフォント・文字サイズ・色を指定できます。縁取りは文字の外側に描画し、色・不透明度・太さを設定します。");
                break;
            case ObjectKind.Text:
                summary = "マスに縛られず文章や見出しを配置する";
                Add("文章と配置", "「文章」欄で文字列を入力します。改行も使えます。グリッド文字とは異なり、1マス1文字に分割しません。移動モードや位置X／Yで置く場所を変更できます。回転はオブジェクトの原点を中心に行います。");
                Add("フォント・サイズ・縁取り", "フォント、文字サイズ、文字色を指定します。縁取りを有効にすると文字の外側に線を付けられます。縁の色・不透明度・太さも指定できます。\n\n文字の範囲は内容とフォントに応じて変わります。固定サイズのキャンバスからはみ出した部分は、書き出し時に切り取られます。");
                break;
            case ObjectKind.Image:
                summary = "画像を自由に置く、またはマスへ収める";
                Add("画像の読み込みとサイズ", "「画像を読み込み／置換」で画像を選びます。画像データはプロジェクトに含まれます。自由配置では位置と幅・高さを指定し、その範囲に画像を縦横比を保って収めます。範囲の比率と画像の比率が違う場合は空きができます。回転は画像の配置範囲の中央を中心に行います。");
                Add("マス座標とマス内配置", "グリッド直下では、左上マスを列1・行1とするマス座標で配置します。小数も入力でき、ドラッグは0.5マス刻みです。マス内配置では、マス全体／余白の内側、9方向の位置合わせ、px単位のずらし量を指定します。新しい画像は余白の内側・中央に収めます。\n\n別のグリッドへ親を変更すると、マス座標と配置設定を引き継いで新しいグリッドに合わせます。自由なpx配置には、グリッドと画像を同じグループの子にしてください。既存ファイルの画像は見た目を保ってマス座標へ変換します。");
                Add("マス切り替えの見本として使う", "マス切り替えの子に置いた画像は見本になります。通常の位置に直接描く代わりに、割り当てた状態のマスへ表示します。グループに入れると、図形の背景や別の画像と組み合わせられます。配置方式の違いはマス切り替えのヘルプで確認できます。");
                break;
            case ObjectKind.Shape:
                summary = "四角・角丸・楕円で背景や目印を作る";
                Add("形・サイズ・見た目", "形を選び、幅・高さ、塗り色、線の色・太さを指定します。線の太さを0にすると輪郭線を描きません。色の不透明度を下げると、背景が透ける図形を作れます。位置X／Yや移動モードで配置し、原点を中心に回転できます。");
                Add("画像と組み合わせる", "レイヤーは上ほど手前に描かれます。図形を画像の下に置くと背景になります。グループにまとめると一緒に移動でき、マス切り替えの見本にも使えます。\n\n親に合わせて配置すれば、外側いっぱいの背景と、内側に収めた画像を組み合わせられます。");
                break;
            case ObjectKind.Line:
                summary = "直線・折れ線・曲線で方向や移動を示す";
                Add("始点・終点・制御点", "位置X／Yが始点です。終点X／Yと制御点X／Yは始点からの相対座標です。\n\n「直線」は始点と終点を直接結びます。「折れ線」は制御点を経由します。「曲線」は制御点の方向へ膨らむカーブです。制御点を上へ離すと、ジャンプする移動のような弧を作れます。曲線は通常、制御点そのものを通りません。");
                Add("ハンドルで編集", "移動モードで選択すると、始点・終点に丸、折れ線の中間点に四角、曲線の制御点にひし形のハンドルを表示します。カーソルを重ねると大きさと色が変わります。始点を動かしても他の点はその場に残ります。Escでドラッグを取り消せます。同じ点の連続編集は1回のUndoにまとまります。親に合わせる配置を使っている場合は、現在の見た目を固定して自由な点編集に切り替えます。");
                Add("矢印と線の見た目", "始点と終点にそれぞれ、なし・三角・開いた矢印を指定できます。矢印の大きさは線の太さと別に設定できます。線の色・太さ・線種も変更できます。");
                Add("マスの中心に合わせる", "グリッド直下では「マス・辺を編集」でクリックすると始点、Shift＋クリックすると終点をマス中央へ配置できます。その時点の座標へ合わせる操作なので、後からマスの大きさを変えても固定追従しません。");
                break;
            case ObjectKind.EdgeSelection:
                summary = "辺ごとに、絵や図形を切り替える";
                Add("状態と見本", "子に画像・図形・文字・ライン・グループを追加し、状態に割り当てます。辺をクリックすると未設定→状態1→状態2→未設定の順で切り替わります。ドラッグ中は最初に選んだ状態を連続して配置します。状態はつまみで並べ替え、ゴミ箱で削除できます。");
                Add("配置と回転", "水平辺を基準に、1マス分の配置範囲を辺の中央に置きます。外周では見本がグリッドの外にも出ます。状態行の表示オブジェクトとゴミ箱の間にある回転ボタンを押すと、垂直辺での向きが0°→右90°→左90°の順に切り替わります。回転は見本ごとに保存され、同じ見本を割り当てた状態には共通で反映されます。グループは全体を回転します。親の外側は1マス分、内側はマス内余白を除いた範囲です。");
                Add("編集対象", "すべて・水平辺のみ・垂直辺のみを切り替えます。対象外の辺も表示・出力されますが、クリックやドラッグでは変更されません。");
                break;
            case ObjectKind.CellSelection:
                summary = "マスごとに、絵や図形を切り替える";
                break;
            default: throw new ArgumentOutOfRangeException(nameof(node.Kind));
        }
        if (SceneDocument.CanUseGridCoordinates(node))
            Add("マス座標とずらし量", "グリッド直下では列・行が置く場所、マス内配置がそのマスに対する収まり方です。例えば列3・行5、余白の内側・左上、ずらし量X=2・Y=2なら、3列5行の余白内の左上から右へ2px、下へ2pxに配置します。列・行を動かしてもずらし量は変わりません。");
        if (node.Kind is ObjectKind.Group or ObjectKind.Grid or ObjectKind.Image or ObjectKind.Text or ObjectKind.Shape or ObjectKind.Line)
            Add("親の配置範囲を使う", "親の外側・内側は、配置の基準として渡される範囲です。内側がない親もあります。親に合わせる配置を有効にすると、配置先と位置合わせを選べます。位置X／Yはそこからのずらし量になります。\n\n「固定」は自身のサイズを維持、「収める」は縦横比を保って拡大・縮小、「広げる」は縦横それぞれを配置先に合わせます。整理用グループやマス配置画像は、それぞれの配置規則に従います。自動サイズのキャンバス直下など、親の範囲が未定義の場合は親合わせを行いません。");
        if (node.Kind != ObjectKind.Canvas)
            Add("グリッド内での移動", "移動モードでは、罫線・グリッド文字・セル塗り・領域枠・マス切り替えは1マス単位で内部の配置を移します。オブジェクトの左上位置は固定です。グリッド直下の画像・図形・フリーテキスト・ライン・変形用グループはマス座標で配置し、拡大率にかかわらず0.5マス刻みで移動します。それ以外の位置はpx単位で、拡大時は倍率に応じた小数単位に揃えます。罫線は線の中心、グリッド文字は配置先のマスがグリッド内に収まる範囲で移動できます。全体を囲む外枠など、移動の余地がない内容は動きません。整理用グループは移動できません。");
        if (node.Kind != ObjectKind.Canvas)
            Add("表示・ロックとレイヤー", "目のアイコンで表示、鍵のアイコンで編集ロックを切り替えます。親を非表示・ロックにすると子にも作用します。レイヤーは同じ階層で上ほど手前に描かれます。ヘルプはロック中も開けます。");
        return (summary, sections);
    }
}
